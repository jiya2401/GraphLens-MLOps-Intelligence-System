"""
Graph Service — loads and queries graph JSON data.

This is the core data access layer. It reads the JSON files
generated by the existing DAG converter and serves them to the API.

Architecture pattern: Service Layer
- Routers handle HTTP (request/response)
- Services handle business logic (data loading, filtering, transforming)
- Models handle data shape (validation, serialization)

This separation means you can test services without HTTP,
swap data sources without changing routes, and keep code clean.

Interview Q: "Why separate routes from business logic?"
Answer: Single Responsibility Principle. Routes handle HTTP concerns
(status codes, headers). Services handle data logic. This makes both
independently testable and swappable.
"""

import json
import logging
from functools import lru_cache
from pathlib import Path

from backend.config import settings

logger = logging.getLogger(__name__)


def _get_data_dir() -> Path:
    """Return the resolved data directory path."""
    return settings.data_path


def _load_json_file(filepath: Path) -> dict:
    """Load and parse a single JSON file."""
    with filepath.open("r", encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=1)
def _discover_graphs() -> dict[int, list[int]]:
    """
    Scan the data directory and build a mapping of graph_id -> [timesteps].

    Uses @lru_cache so we only scan the filesystem once.
    Subsequent calls return the cached result instantly.

    Interview Q: "What is @lru_cache and when should you use it?"
    Answer: LRU (Least Recently Used) cache is a decorator that memoizes
    function results. Use it for expensive computations with the same inputs.
    Here we avoid re-scanning 500 files on every API call.
    """
    data_dir = _get_data_dir()
    graphs: dict[int, list[int]] = {}

    if not data_dir.exists():
        logger.warning(f"Data directory not found: {data_dir}")
        return graphs

    for filepath in sorted(data_dir.glob("graph_*_t*.json")):
        try:
            # Parse filename: graph_000_t00.json -> graph_id=0, timestep=0
            parts = filepath.stem.split("_")
            graph_id = int(parts[1])
            timestep = int(parts[2][1:])  # Remove 't' prefix
            graphs.setdefault(graph_id, []).append(timestep)
        except (IndexError, ValueError) as e:
            logger.warning(f"Skipping malformed filename {filepath.name}: {e}")

    # Sort timesteps for each graph
    for graph_id in graphs:
        graphs[graph_id].sort()

    logger.info(f"Discovered {len(graphs)} graphs in {data_dir}")
    return graphs


def _get_json_path(graph_id: int, timestep: int) -> Path:
    """Build the file path for a specific graph + timestep."""
    return _get_data_dir() / f"graph_{graph_id:03d}_t{timestep:02d}.json"


def get_all_graphs_summary() -> list[dict]:
    """
    Return a summary list of all available graphs.
    Reads only the t=0 snapshot for each graph to build the summary.
    """
    graph_map = _discover_graphs()
    summaries = []

    for graph_id, timesteps in sorted(graph_map.items()):
        filepath = _get_json_path(graph_id, timesteps[0])
        if not filepath.exists():
            continue

        try:
            data = _load_json_file(filepath)
            nodes = data.get("nodes", [])
            edges = data.get("edges", [])
            prop_stats = data.get("propagation_stats", {})

            # Count health statuses
            health_summary = {"healthy": 0, "warning": 0, "unstable": 0, "failed": 0}
            for node in nodes:
                health = node.get("health", "unknown")
                if health in health_summary:
                    health_summary[health] += 1

            summaries.append(
                {
                    "graph_id": graph_id,
                    "total_nodes": len(nodes),
                    "total_edges": len(edges),
                    "total_timesteps": len(timesteps),
                    "failure_rate": prop_stats.get("failure_rate", 0.0),
                    "avg_anomaly_score": prop_stats.get("avg_anomaly_score", 0.0),
                    "health_summary": health_summary,
                }
            )
        except Exception as e:
            logger.error(f"Error reading graph {graph_id}: {e}")

    return summaries


def get_graph(graph_id: int, timestep: int = 0) -> dict | None:
    """
    Load a single graph at a specific timestep.
    Returns None if not found.
    """
    filepath = _get_json_path(graph_id, timestep)
    if not filepath.exists():
        logger.warning(f"Graph file not found: {filepath}")
        return None

    return _load_json_file(filepath)


def get_node_detail(
    node_id: str, graph_id: int = 0, timestep: int = 0
) -> dict | None:
    """
    Get detailed info for a specific node, including its dependencies.
    """
    graph_data = get_graph(graph_id, timestep)
    if not graph_data:
        return None

    # Find the node
    target_node = None
    for node in graph_data.get("nodes", []):
        if node["id"] == node_id:
            target_node = node
            break

    if not target_node:
        return None

    # Find dependencies from edges
    edges = graph_data.get("edges", [])
    incoming = [e["source"] for e in edges if e["target"] == node_id]
    outgoing = [e["target"] for e in edges if e["source"] == node_id]

    return {
        "node": target_node,
        "graph_id": graph_id,
        "timestep": timestep,
        "incoming_dependencies": incoming,
        "outgoing_dependencies": outgoing,
    }


def get_available_graph_ids() -> list[int]:
    """Return sorted list of all available graph IDs."""
    return sorted(_discover_graphs().keys())


def get_timesteps_for_graph(graph_id: int) -> list[int]:
    """Return sorted list of timesteps available for a graph."""
    graph_map = _discover_graphs()
    return graph_map.get(graph_id, [])
